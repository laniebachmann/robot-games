//------------------------------------//
// Session info (replaces the Flask session).
// Carried from page to page in the URL: ?id=<subject ID>&s=<session code>
//------------------------------------//

var URL_PARAMS   = new URLSearchParams(window.location.search);
var SUBJECT_ID   = URL_PARAMS.get('id');
var SESSION_CODE = URL_PARAMS.get('s');

// Prolific: launch with  index.html?PROLIFIC_PID={{%PROLIFIC_PID%}}&STUDY_ID={{%STUDY_ID%}}&SESSION_ID={{%SESSION_ID%}}
// (index.html sets id = PROLIFIC_PID). Completion code is from the study's settings on Prolific.
var PROLIFIC_COMPLETION_CODE = 'CGBJ9RCY';
var PROLIFIC_PID = URL_PARAMS.get('PROLIFIC_PID');
var STUDY_ID     = URL_PARAMS.get('STUDY_ID');
var SESSION_ID   = URL_PARAMS.get('SESSION_ID');
var IS_PROLIFIC  = !!PROLIFIC_PID;
var CONSENT_TIME         = URL_PARAMS.get('ct');    // time Start was clicked on the consent page
var CONSENT_CHECKED_TIME = URL_PARAMS.get('cc');    // time the "I agree to participate" box was ticked
var CONSENT_RT           = URL_PARAMS.get('crt');   // ms spent on the consent page

// Palminteri learning accuracy (%), carried from the Palminteri page to the PIT page so the
// overall accuracy and bonus can be computed at the end. Set by pass_data_palminteri().
var LEARNING_ACC = (URL_PARAMS.get('la') === null) ? null : Number(URL_PARAMS.get('la'));

// Running inside index.html's full-screen frame? (Then pages never request full screen themselves.)
var IN_SHELL = (window.self !== window.top);

// Missing session info -> back to the start page.
if (!SUBJECT_ID || !SESSION_CODE) {
  window.top.location.replace('index.html' + window.location.search);
}

// Make sure key presses reach this page after each page change inside the frame.
window.addEventListener('load', function() { window.focus(); });

// Attach to every jsPsych trial.
jsPsych.data.addProperties({
  subject_id:   SUBJECT_ID,
  session_code: SESSION_CODE,
  user_agent:   navigator.userAgent,
  prolific_pid: PROLIFIC_PID,
  study_id:     STUDY_ID,
  prolific_session_id: SESSION_ID,
  consent_form: 'IRB-AAAI1488 (Y17M00)',
  consent_time: CONSENT_TIME,
  consent_checked_time: CONSENT_CHECKED_TIME,
  consent_rt: (CONSENT_RT === null ? null : Number(CONSENT_RT)),
});

// Move to the next page, keeping the session info.
function go_to(page) {
  var params = {id: SUBJECT_ID, s: SESSION_CODE};
  if (IS_PROLIFIC) { params.PROLIFIC_PID = PROLIFIC_PID; params.STUDY_ID = STUDY_ID; params.SESSION_ID = SESSION_ID; }
  if (CONSENT_TIME) { params.ct = CONSENT_TIME; params.cc = CONSENT_CHECKED_TIME; params.crt = CONSENT_RT; }
  if (LEARNING_ACC !== null) { params.la = LEARNING_ACC; }
  var q = new URLSearchParams(params);
  window.location.href = page + '?' + q.toString();
}

//------------------------------------//
// Automation flags (bot screening; recorded in the saved data, nothing is shown).
//   webdriver:        true when the browser reports it is under automation control
//   untrusted_keys:   key presses on this page generated by a script, not a keyboard
//   untrusted_clicks: clicks on this page generated by a script, not a mouse
// Real participants should always have false / 0 / 0.
//------------------------------------//
var BOT_FLAGS = {webdriver: (navigator.webdriver === true), untrusted_keys: 0, untrusted_clicks: 0};
window.addEventListener('keydown', function(e) { if (!e.isTrusted) BOT_FLAGS.untrusted_keys++; }, true);
window.addEventListener('click',   function(e) { if (!e.isTrusted) BOT_FLAGS.untrusted_clicks++; }, true);

